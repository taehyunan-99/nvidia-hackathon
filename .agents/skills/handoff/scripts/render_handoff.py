def output_snapshot(path: Path) -> tuple[bool, int, int, str]:
    if is_link_path(path):
        fail(f"output must not be a link or junction: {path}")
    if not path.exists():
        return (False, 0, 0, "")
    info = path.stat()
    if not stat.S_ISREG(info.st_mode):
        fail(f"output must be a regular file: {path}")
    if info.st_size > MAX_OUTPUT_BYTES:
        fail(f"existing generated HTML is unexpectedly large: {path}")
    raw = path.read_bytes()
    first_line = raw.splitlines()[0].decode("utf-8", errors="replace") if raw else ""
    if re.fullmatch(
        r"<!-- Generated by Handoff renderer; source-sha256=[0-9a-f]{64} -->",
        first_line,
    ) is None:
        fail(f"refusing to overwrite non-generated HTML: {path}")
    return (
        True,
        info.st_mtime_ns,
        info.st_size,
        hashlib.sha256(raw).hexdigest(),
    )


def directory_identity(path: Path) -> tuple[int, int]:
    info = path.stat()
    if not stat.S_ISDIR(info.st_mode):
        fail(f"output parent must be a directory: {path}")
    return (info.st_dev, info.st_ino)


def require_output_parent(
    root: Path,
    output: Path,
    expected_identity: tuple[int, int],
) -> None:
    reject_link_components(root, output)
    if directory_identity(output.parent) != expected_identity:
        fail(f"output parent changed during render: {output.parent}")


def acquire_lock(
    root: Path,
    output: Path,
    parent_identity: tuple[int, int],
) -> tuple[Path, str]:
    require_output_parent(root, output, parent_identity)
    lock_path = output.with_name(output.name + ".handoff-render.lock")
    token = uuid.uuid4().hex
    try:
        descriptor = os.open(
            lock_path,
            os.O_CREAT | os.O_EXCL | os.O_WRONLY,
            0o600,
        )
    except FileExistsError:
        fail(f"render lock exists: {lock_path}")
    with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(token + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    return lock_path, token


def release_lock(
    root: Path,
    output: Path,
    parent_identity: tuple[int, int],
    lock_path: Path,
    token: str,
) -> None:
    require_output_parent(root, output, parent_identity)
    if not lock_path.exists() or is_link_path(lock_path):
        fail(f"render lock changed before cleanup: {lock_path}")
    content = lock_path.read_text(encoding="utf-8").strip()
    if content != token:
        fail(f"render lock ownership changed: {lock_path}")
    lock_path.unlink()


def write_atomic(
    root: Path,
    output: Path,
    content: str,
    original_snapshot: tuple[bool, int, int, str],
    parent_identity: tuple[int, int],
) -> None:
    require_output_parent(root, output, parent_identity)
    current_snapshot = output_snapshot(output)
    if current_snapshot != original_snapshot:
        fail(f"output changed during render: {output}")
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=".handoff-report-",
        suffix=".tmp",
        dir=output.parent,
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        require_output_parent(root, output, parent_identity)
        os.replace(temporary, output)
    finally:
        if temporary.exists():
            temporary.unlink()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", required=True)
    parser.add_argument("--handoff", default="docs/HANDOFF.md")
    parser.add_argument("--output", default="docs/HANDOFF.html")
    return parser.parse_args()


def main() -> int:
    lock_path: Path | None = None
    lock_token: str | None = None
    root: Path | None = None
    output: Path | None = None
    parent_identity: tuple[int, int] | None = None
    try:
        args = parse_args()
        lexical_root = Path(os.path.abspath(Path(args.project_root)))
        if is_link_path(lexical_root):
            fail(f"project root must not be a link or junction: {lexical_root}")
        root = lexical_root.resolve(strict=True)
        if not root.is_dir():
            fail(f"project root must be a real directory: {root}")
        source = resolve_inside(root, args.handoff, must_exist=True)
        output = resolve_inside(root, args.output, must_exist=False)
        if source == output:
            fail("handoff source and HTML output must differ")
        output.parent.mkdir(parents=True, exist_ok=True)
        reject_link_components(root, output)
        parent_identity = directory_identity(output.parent)

        source_raw = read_regular_utf8(source)
        source_sha256 = hashlib.sha256(source_raw).hexdigest()
        model = parse_handoff(source_raw.decode("utf-8"))
        require_output_parent(root, output, parent_identity)
        original_output = output_snapshot(output)
        lock_path, lock_token = acquire_lock(
            root,
            output,
            parent_identity,
        )
        rendered = render_html(model, source_sha256)
        if read_regular_utf8(source) != source_raw:
            fail(f"handoff changed during render: {source}")
        write_atomic(
            root,
            output,
            rendered,
            original_output,
            parent_identity,
        )
        release_lock(
            root,
            output,
            parent_identity,
            lock_path,
            lock_token,
        )
        lock_path = None
        lock_token = None
        print(str(output))
        return 0
    except (HandoffError, OSError) as exc:
        print(f"handoff report error: {exc}", file=sys.stderr)
        return 2
    finally:
        if (
            root is not None
            and output is not None
            and parent_identity is not None
            and lock_path is not None
            and lock_token is not None
        ):
            try:
                release_lock(
                    root,
                    output,
                    parent_identity,
                    lock_path,
                    lock_token,
                )
            except (HandoffError, OSError) as exc:
                print(f"handoff report cleanup error: {exc}", file=sys.stderr)


if __name__ == "__main__":
    raise SystemExit(main())
