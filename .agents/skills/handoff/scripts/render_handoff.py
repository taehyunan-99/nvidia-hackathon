def parse_work_summary(lines: list[str]) -> dict[str, str] | None:
    heading_indexes = [
        index
        for index, line in enumerate(lines)
        if line.strip() == WORK_SUMMARY_HEADING
    ]
    if len(heading_indexes) > 1:
        fail("Resume instructions has duplicate 작업 결과 요약 headings")
    if not heading_indexes:
        return None
    values: dict[str, str] = {}
    order: list[str] = []
    for line in lines[heading_indexes[0] + 1 :]:
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("### "):
            fail("작업 결과 요약 must be the final Resume instructions subsection")
        match = re.fullmatch(r"-\s+([^:\n]+):\s*(.+)", stripped)
        if match is None:
            fail("작업 결과 요약 must contain only '- 항목: 내용' lines")
        key = match.group(1).strip()
        if key in values:
            fail(f"duplicate 작업 결과 요약 field: {key}")
        if key not in WORK_SUMMARY_FIELDS:
            fail(f"unknown 작업 결과 요약 field: {key}")
        values[key] = nonempty(match.group(2), f"작업 결과 요약.{key}")
        order.append(key)
    if tuple(order) != WORK_SUMMARY_FIELDS:
        fail("작업 결과 요약 fields must appear in the required order")
    return values


def is_link_path(path: Path) -> bool:
    if path.is_symlink():
        return True
    if os.name == "nt" and path.exists():
        attributes = getattr(os.lstat(path), "st_file_attributes", 0)
        reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
        if attributes & reparse_flag:
            return True
    junction_check = getattr(path, "is_junction", None)
    return bool(junction_check and junction_check())


def reject_link_components(root: Path, target: Path) -> None:
    try:
        relative = target.relative_to(root)
    except ValueError:
        fail(f"path escapes project root: {target}")
    current = root
    if is_link_path(current):
        fail(f"project root must not be a link or junction: {root}")
    for part in relative.parts:
        current = current / part
        if current.exists() and is_link_path(current):
            fail(f"managed path contains a link or junction: {current}")


def resolve_inside(root: Path, raw: str, *, must_exist: bool) -> Path:
    candidate = Path(raw)
    if not candidate.is_absolute():
        candidate = root / candidate
    lexical = Path(os.path.abspath(candidate))
    try:
        lexical.relative_to(root)
    except ValueError:
        fail(f"path escapes project root: {raw}")
    reject_link_components(root, lexical)
    resolved = lexical.resolve(strict=must_exist)
    try:
        resolved.relative_to(root)
    except ValueError:
        fail(f"path escapes project root: {raw}")
    return resolved


def read_regular_utf8(path: Path) -> bytes:
    with path.open("rb") as handle:
        before = os.fstat(handle.fileno())
        if not stat.S_ISREG(before.st_mode):
            fail(f"input must be a regular file: {path}")
        if before.st_size > MAX_FILE_BYTES:
            fail(f"input is too large: {path}")
        raw = handle.read(MAX_FILE_BYTES + 1)
        after = os.fstat(handle.fileno())
    if len(raw) > MAX_FILE_BYTES:
        fail(f"input is too large: {path}")
    identity_before = (
        before.st_dev,
        before.st_ino,
        before.st_size,
        before.st_mtime_ns,
    )
    identity_after = (
        after.st_dev,
        after.st_ino,
        after.st_size,
        after.st_mtime_ns,
    )
    if identity_before != identity_after:
        fail(f"input changed while being read: {path}")
    if b"\x00" in raw:
        fail(f"input contains a null byte: {path}")
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        fail(f"input must be UTF-8: {exc}")
    return raw


def nonempty(value: str, path: str) -> str:
    result = value.strip()
    if not result:
        fail(f"{path} must not be empty")
    return result


def split_pipe_row(line: str) -> list[str]:
    stripped = line.strip()
    if stripped.startswith("|"):
        stripped = stripped[1:]
    if stripped.endswith("|"):
        stripped = stripped[:-1]
    cells: list[str] = []
    current: list[str] = []
    escaped = False
    for character in stripped:
        if escaped:
            if character != "|":
                current.append("\\")
            current.append(character)
            escaped = False
        elif character == "\\":
            escaped = True
        elif character == "|":
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(character)
    if escaped:
        current.append("\\")
    cells.append("".join(current).strip())
    return cells


def is_table_separator(cells: list[str]) -> bool:
    return bool(cells) and all(
        re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) is not None
        for cell in cells
    )


def parse_table(lines: list[str], section: str) -> dict[str, Any]:
    table_lines = [line for line in lines if line.strip().startswith("|")]
    if len(table_lines) < 2:
        fail(f"{section} must contain a Markdown table")
    header = split_pipe_row(table_lines[0])
    separator = split_pipe_row(table_lines[1])
    if len(separator) != len(header) or not is_table_separator(separator):
        fail(f"{section} has an invalid table separator")
    expected = TABLE_SCHEMAS.get(section, STAGE_TABLE_SCHEMA)
    if header != expected:
        fail(
            f"{section} table columns must be exactly: "
            + " | ".join(expected)
        )
    rows: list[dict[str, str]] = []
    for index, line in enumerate(table_lines[2:], start=1):
        cells = split_pipe_row(line)
        if len(cells) != len(header):
            fail(f"{section} row {index} has the wrong number of cells")
        row = {name: nonempty(value, f"{section} row {index}.{name}") for name, value in zip(header, cells)}
        rows.append(row)
    if not rows:
        fail(f"{section} table must contain at least one data row")
    return {"headers": header, "rows": rows}


def parse_metadata(lines: list[str]) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        match = METADATA_PATTERN.fullmatch(stripped)
        if match is None:
            fail(f"invalid metadata line: {stripped}")
        key = match.group(1).strip()
        if key in values:
            fail(f"duplicate metadata field: {key}")
        values[key] = nonempty(match.group(2), key)
    missing = REQUIRED_METADATA - values.keys()
    extra = values.keys() - REQUIRED_METADATA
    if missing:
        fail("missing metadata fields: " + ", ".join(sorted(missing)))
    if extra:
        fail("unknown metadata fields: " + ", ".join(sorted(extra)))
    if values["Format"] not in SUPPORTED_FORMATS:
        fail(
            "Format must be handoff-v2, handoff-v3, handoff-v4, "
            "handoff-v5, handoff-v6, handoff-v7, or handoff-v8"
        )
    if values["Receipt"] not in RECEIPT_STATUSES:
        fail("Receipt has an unsupported value")
    if values["Work status"] not in WORK_STATUSES:
        fail("Work status has an unsupported value")
    raw_scope = values["Project scope"]
    project_scope = PurePosixPath(raw_scope)
    if (
        "\\" in raw_scope
        or project_scope.is_absolute()
        or ".." in project_scope.parts
        or raw_scope not in {".", project_scope.as_posix()}
    ):
        fail("Project scope must be . or a safe Git-relative POSIX path")
    timestamp = values["Last verified"].replace("Z", "+00:00")
    try:
        verified_at = datetime.fromisoformat(timestamp)
    except ValueError:
        fail("Last verified must be an ISO 8601 timestamp with timezone")
    if verified_at.tzinfo is None or verified_at.utcoffset() is None:
        fail("Last verified must include a timezone")
    return values


def split_sections(lines: list[str]) -> tuple[list[str], dict[str, list[str]]]:
    metadata_lines: list[str] = []
    sections: dict[str, list[str]] = {}
    current: str | None = None
    in_fence = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            if current is None:
                fail("metadata must not contain fenced code")
            sections[current].append(line)
            in_fence = not in_fence
            continue
        if not in_fence and line.startswith("## "):
            name = line[3:].strip()
            if name in sections:
                fail(f"duplicate section: {name}")
            sections[name] = []
            current = name
            continue
        if current is None:
            metadata_lines.append(line)
        else:
            sections[current].append(line)
    if in_fence:
        fail("document contains an unclosed fenced code block")
    missing = [name for name in REQUIRED_SECTIONS if name not in sections]
    extra = [name for name in sections if name not in REQUIRED_SECTIONS]
    if missing:
        fail("missing sections: " + ", ".join(missing))
    if extra:
        fail("unknown sections: " + ", ".join(extra))
    if list(sections) != REQUIRED_SECTIONS:
        fail("sections must appear in the required order")
    for name, section_lines in sections.items():
        if not any(line.strip() for line in section_lines):
            fail(f"{name} must not be empty")
    return metadata_lines, sections


def parse_stage_metadata(lines: list[str], stage_id: str) -> dict[str, str]:
    required = {
        "State",
        "Maps to",
        "Outcome",
        "Scope",
        "Verification",
        "First action",
    }
    values: dict[str, str] = {}
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("|"):
            continue
        match = METADATA_PATTERN.fullmatch(stripped)
        if match is None:
            fail(f"{stage_id} has invalid metadata: {stripped}")
        key = match.group(1).strip()
        if key in values:
            fail(f"{stage_id} has duplicate metadata: {key}")
        values[key] = nonempty(match.group(2), f"{stage_id}.{key}")
    missing = required - values.keys()
    extra = values.keys() - required
    if missing:
        fail(f"{stage_id} is missing: " + ", ".join(sorted(missing)))
    if extra:
        fail(f"{stage_id} has unknown metadata: " + ", ".join(sorted(extra)))
    if values["State"] not in STAGE_STATES:
        fail(f"{stage_id}.State has an unsupported value")
    return values


def parse_stages(lines: list[str]) -> list[dict[str, Any]]:
    content = [line.strip() for line in lines if line.strip()]
    if content == ["No remaining stages."]:
        return []

    stages: list[dict[str, Any]] = []
    current_heading: str | None = None
    current_lines: list[str] = []
    preface: list[str] = []
    in_fence = False

    def append_current() -> None:
        if current_heading is None:
            return
        match = STAGE_HEADING_PATTERN.fullmatch(current_heading)
        if match is None:
            fail(f"invalid stage heading: {current_heading}")
        stage_id = match.group(1)
        if any(stage["id"] == stage_id for stage in stages):
            fail(f"duplicate stage id: {stage_id}")
        metadata = parse_stage_metadata(current_lines, stage_id)
        table = parse_table(current_lines, stage_id)
        stages.append(
            {
                "id": stage_id,
                "name": nonempty(match.group(2), f"{stage_id}.name"),
                "metadata": metadata,
                "table": table,
            }
        )

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("### "):
            append_current()
            current_heading = line[4:].strip()
            current_lines = []
        elif current_heading is None:
            if line.strip():
                preface.append(line)
        else:
            current_lines.append(line)
    if in_fence:
        fail("Execution plan contains an unclosed fenced code block")
    append_current()
    if preface:
        fail("Execution plan must contain only stage subsections")
    if not stages:
        fail(
            "Execution plan must contain a stage or exactly "
            "'No remaining stages.'"
        )
    return stages



def parse_routing(lines: list[str], format_name: str) -> dict[str, str] | None:
    heading_indexes = [
        index
        for index, line in enumerate(lines)
        if line.strip() == ROUTING_HEADING
    ]
    if len(heading_indexes) > 1:
        fail("Required context has duplicate Next-stage routing headings")
    if not heading_indexes:
        return None

    routing_fields = (
        V7_ROUTING_FIELDS
        if format_name in {"handoff-v7", "handoff-v8"}
        else V6_ROUTING_FIELDS
        if format_name == "handoff-v6"
        else LEGACY_ROUTING_FIELDS
    )
    values: dict[str, str] = {}
    order: list[str] = []
    start = heading_indexes[0] + 1
    for line in lines[start:]:
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("### "):
            fail("Next-stage routing must be the final Required context subsection")
        match = re.fullmatch(r"-\s+([^:\n]+):\s*(.+)", stripped)
        if match is None:
            fail("Next-stage routing must contain only '- Key: value' lines")
        key = match.group(1).strip()
        if key in values:
            fail(f"duplicate next-stage routing field: {key}")
        if key not in routing_fields:
            fail(f"unknown next-stage routing field: {key}")
        values[key] = nonempty(match.group(2), f"Next-stage routing.{key}")
        order.append(key)

    missing = [key for key in routing_fields if key not in values]
    if missing:
        fail("missing next-stage routing fields: " + ", ".join(missing))
    if tuple(order) != routing_fields:
        fail("next-stage routing fields must appear in the required order")
    return values
def parse_continuation(lines: list[str]) -> dict[str, str] | None:
    heading_indexes = [
        index
        for index, line in enumerate(lines)
        if line.strip() == CONTINUATION_HEADING
    ]
    if len(heading_indexes) > 1:
        fail("Required context has duplicate Continuation decision headings")
    if not heading_indexes:
        return None
    start = heading_indexes[0] + 1
    end = next(
        (
            index
            for index in range(start, len(lines))
            if lines[index].strip().startswith("### ")
        ),
        len(lines),
    )
    values: dict[str, str] = {}
    order: list[str] = []
    for line in lines[start:end]:
        stripped = line.strip()
        if not stripped:
            continue
        match = re.fullmatch(r"-\s+([^:\n]+):\s*(.+)", stripped)
        if match is None:
            fail("Continuation decision must contain only '- Key: value' lines")
        key = match.group(1).strip()
        if key in values:
            fail(f"duplicate continuation decision field: {key}")
        if key not in CONTINUATION_FIELDS:
            fail(f"unknown continuation decision field: {key}")
        values[key] = nonempty(match.group(2), f"Continuation decision.{key}")
        order.append(key)
    if tuple(order) != CONTINUATION_FIELDS:
        fail("Continuation decision fields must appear in the required order")
    return values


def parse_completion_checklist(lines: list[str]) -> dict[str, dict[str, str]] | None:
    heading_indexes = [
        index
        for index, line in enumerate(lines)
        if line.strip() == CHECKLIST_HEADING
    ]
    if len(heading_indexes) > 1:
        fail("State verification has duplicate Handoff completion checklist headings")
    if not heading_indexes:
        return None
    start = heading_indexes[0] + 1
    values: dict[str, dict[str, str]] = {}
    for line in lines[start:]:
        stripped = line.strip()
        if not stripped:
            continue
        match = re.fullmatch(r"-\s+([a-z-]+):\s+(PASS|FAIL|UNVERIFIED);\s*(.+)", stripped)
        if match is None:
            fail("Handoff completion checklist must contain only '- check: STATUS; evidence' lines")
        key, status, evidence = match.groups()
        if key in values:
            fail(f"duplicate handoff completion checklist item: {key}")
        values[key] = {"Status": status, "Evidence": nonempty(evidence, key)}
    if not values:
        fail("Handoff completion checklist must contain at least one item")
    return values

def evidence_ids(value: str) -> set[str]:
    return set(EVIDENCE_ID_PATTERN.findall(value))


def validate_model(model: dict[str, Any]) -> None:
    metadata = model["metadata"]
    tables = model["tables"]
    stages = model["stages"]

    evidence_rows = tables["Evidence"]["rows"]
    evidence_index: dict[str, dict[str, str]] = {}
    for row in evidence_rows:
        item_id = row["ID"]
        if re.fullmatch(r"E[1-9][0-9]*", item_id) is None:
            fail(f"invalid evidence id: {item_id}")
        if item_id in evidence_index:
            fail(f"duplicate evidence id: {item_id}")
        if row["Result"] not in CRITERION_STATUSES:
            fail(f"{item_id}.Result must be PASS, FAIL, or UNVERIFIED")
        evidence_index[item_id] = row

    def require_pass_evidence(refs: set[str], subject: str) -> None:
        non_passing = sorted(
            item_id
            for item_id in refs
            if evidence_index[item_id]["Result"] != "PASS"
        )
        if non_passing:
            fail(f"{subject} PASS references non-PASS evidence: {non_passing}")

