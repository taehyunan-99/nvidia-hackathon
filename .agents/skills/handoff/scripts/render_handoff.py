def extract_prompt(lines: list[str], work_status: str, format_name: str) -> str | None:
    nonblank = [line.strip() for line in lines if line.strip()]
    if format_name in {"handoff-v4", "handoff-v5", "handoff-v6", "handoff-v7", "handoff-v8"}:
        if nonblank != [NO_COPYABLE_PROMPT]:
            fail("handoff-v4, handoff-v5, and handoff-v6 must use exactly the no-copyable-prompt marker")
        return None
    if work_status == "COMPLETE":
        if nonblank != ["No new-session prompt: work is complete."]:
            fail(
                "COMPLETE work must use exactly "
                "'No new-session prompt: work is complete.'"
            )
        return None

    fence_indexes = [
        index
        for index, line in enumerate(lines)
        if line.strip().startswith("```")
    ]
    if len(fence_indexes) != 2:
        fail("New-session prompt must contain exactly one closed fenced block")
    start, end = fence_indexes
    if any(line.strip() for line in lines[:start] + lines[end + 1 :]):
        fail("New-session prompt must contain only its fenced block")
    collected = lines[start + 1 : end]
    return nonempty("\n".join(collected), "New-session prompt")


def parse_handoff(text: str) -> dict[str, Any]:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.split("\n")
    if not lines or lines[0].strip() != "# HANDOFF":
        fail("document must begin with # HANDOFF")
    metadata_lines, sections = split_sections(lines[1:])
    metadata = parse_metadata(metadata_lines)
    parallel = None
    if metadata["Format"] == "handoff-v8" or "### Parallel execution" in normalized:
        import importlib.util
        location = Path(__file__).with_name("parallel_contract.py")
        contract_spec = importlib.util.spec_from_file_location("_handoff_parallel", location)
        contract = importlib.util.module_from_spec(contract_spec)
        contract_spec.loader.exec_module(contract)
        try:
            parallel = contract.extract(normalized)
            if metadata["Format"] != "handoff-v8" or parallel is None:
                fail("parallel execution requires handoff-v8 and exactly one state block")
            state_text = "\n".join(sections["State verification"])
            if contract.extract(state_text) != parallel:
                fail("parallel state must be inside State verification")
            sections["State verification"] = contract.without_block(state_text).split("\n")
            if metadata["Receipt"] == "READY" and parallel["phase"] in {"ACTIVE", "STOPPING"}:
                fail("live parallel execution cannot be a READY receipt")
            if metadata["Work status"] == "COMPLETE" and parallel["phase"] != "COMPLETE":
                fail("complete receipt has unfinished parallel execution")
        except (contract.ParallelError, ValueError, TypeError, KeyError) as exc:
            fail(f"invalid parallel state: {exc}")
    tables = {
        name: parse_table(sections[name], name)
        for name in TABLE_SCHEMAS
    }
    stages = parse_stages(sections["Execution plan"])
    model = {
        "metadata": metadata,
        "sections": sections,
        "tables": tables,
        "stages": stages,
        "routing": parse_routing(
            sections["Required context"],
            metadata["Format"],
        ),
        "continuation": parse_continuation(sections["Required context"]),
        "checklist": parse_completion_checklist(sections["State verification"]),
        "work_summary": parse_work_summary(sections["Resume instructions"]),
        "prompt": extract_prompt(
            sections["New-session prompt"],
            metadata["Work status"],
            metadata["Format"],
        ),
    }
    model["parallel"] = parallel
    validate_model(model)
    if parallel is not None and parallel["phase"] != "COMPLETE":
        route = model["routing"]
        if not route or route["Current stage"].split(" ", 1)[0] != parallel["plan"]["stage_id"] or route["Goal"] != parallel["plan"]["goal"] or route["Use Ultra"] != "yes":
            fail("parallel plan must match the selected independent stage")
    return model


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def status_class(value: str) -> str:
    if value in {"READY", "COMPLETE", "PASS", "ALIGNED"}:
        return "good"
    if value in {"INVALID", "FAIL", "CONFLICT"}:
        return "bad"
    if value in {"STALE", "BLOCKED", "UNVERIFIED"}:
        return "warn"
    return "neutral"


def render_inline(value: str) -> str:
    output: list[str] = []
    cursor = 0
    for match in re.finditer(r"`([^`\n]+)`", value):
        output.append(esc(value[cursor : match.start()]))
        output.append("<code>" + esc(match.group(1)) + "</code>")
        cursor = match.end()
    output.append(esc(value[cursor:]))
    return "".join(output)


def render_simple_markdown(lines: list[str]) -> str:
    output: list[str] = []
    paragraph: list[str] = []
    list_kind: str | None = None
    in_code = False
    code_lines: list[str] = []

    def flush_paragraph() -> None:
        if paragraph:
            output.append("<p>" + render_inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()

    def close_list() -> None:
        nonlocal list_kind
        if list_kind is not None:
            output.append(f"</{list_kind}>")
            list_kind = None

    for raw_line in lines:
        line = raw_line.rstrip()
        stripped = line.strip()
        if stripped.startswith("```"):
            flush_paragraph()
            close_list()
            if in_code:
                output.append("<pre><code>" + esc("\n".join(code_lines)) + "</code></pre>")
                code_lines = []
                in_code = False
            else:
                in_code = True
            continue
        if in_code:
            code_lines.append(line)
            continue
        if not stripped:
            flush_paragraph()
            close_list()
            continue
        if stripped.startswith("|"):
            continue
        if stripped.startswith("### "):
            flush_paragraph()
            close_list()
            output.append("<h3>" + render_inline(stripped[4:]) + "</h3>")
            continue
        unordered = re.match(r"^[-*]\s+(.*)$", stripped)
        ordered = re.match(r"^[0-9]+\.\s+(.*)$", stripped)
        if unordered or ordered:
            flush_paragraph()
            desired = "ul" if unordered else "ol"
            if list_kind != desired:
                close_list()
                output.append(f"<{desired}>")
                list_kind = desired
            item = unordered.group(1) if unordered else ordered.group(1)
            output.append("<li>" + render_inline(item) + "</li>")
            continue
        close_list()
        paragraph.append(stripped)
    if in_code:
        fail("unclosed fenced code block")
    flush_paragraph()
    close_list()
    return "".join(output)


def render_table(table: dict[str, Any], *, first_column_header: bool = False) -> str:
    headers = table["headers"]
    head = "".join(f"<th scope=col>{esc(value)}</th>" for value in headers)
    rows: list[str] = []
    for row in table["rows"]:
        cells: list[str] = []
        for index, header in enumerate(headers):
            value = row[header]
            tag = "th scope=row" if first_column_header and index == 0 else "td"
            css = status_class(value)
            cells.append(f"<{tag} class={css}>{render_inline(value)}</{tag.split()[0]}>")
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return "<div class=table-wrap><table><thead><tr>" + head + "</tr></thead><tbody>" + "".join(rows) + "</tbody></table></div>"


def load_font_data() -> str:
    font_path = Path(__file__).resolve().parents[1] / "assets" / "PretendardVariable.woff2"
    if not font_path.is_file() or is_link_path(font_path):
        fail(f"bundled font is missing or unsafe: {font_path}")
    raw = font_path.read_bytes()
    if len(raw) > 3_000_000:
        fail("bundled font is unexpectedly large")
    return base64.b64encode(raw).decode("ascii")


